/// @brief Convert little-endian byte array to int32_t right padded proportionally (i.e. 16 bit to upper 16 bits of
/// int32_t). For use with writeTxFrames
/// @param src Little-endian source byte array
/// @param bytesPerSample Size of source sample in bytes
/// @return Resulting int32_t sample
inline int32_t littleEndianToInt32(const uint8_t * src, unsigned bytesPerSample)
{
	// Use uint32_t for bit manipulation
	uint32_t val = 0;
	// Duff's device for little endian integer format conversion to 32 bit
	switch (bytesPerSample)
	{
	case 4:
		val |= (uint32_t)(*src++) << 0;
		// fallthrough
	case 3:
		val |= (uint32_t)(*src++) << 8;
		// fallthrough
	default: // We support a minimum of 16 bits
		val |= (uint32_t)(*src++) << 16;
		val |= (uint32_t)(*src) << 24;
		break;
	}
	int32_t rval = 0;
	std::memcpy(&rval, &val, sizeof(int32_t));
	return rval;
}

/// @brief Convert int32_t sample to little-endian byte array truncating least significant bytes as needed. For use with
/// readRxFrames
/// @param dst Destination little-endian byte array
/// @param sample Source int32_t sample
/// @param bytesPerSample Size of destination sample in bytes
inline void int32ToLittleEndian(uint8_t * dst, int32_t sample, unsigned bytesPerSample)
{
	// Convert int32_t to uint32_t for bit manipulation
	uint32_t val = 0;
	std::memcpy(&val, &sample, sizeof(int32_t));
	// Duff's device for little endian integer format conversion from 32 bit
	switch (bytesPerSample)
	{
	case 4:
		*dst++ = (val >> 0) & 0xff;
		// fallthrough
	case 3:
		*dst++ = (val >> 8) & 0xff;
		// fallthrough
	default: // Minimum 16 bits
		*dst++ = (val >> 16) & 0xff;
		*dst = (val >> 24) & 0xff;
		break;
	}
}

/// @brief Convert native endianness byte array to int32_t. For use with writeTxFrames
/// @param src uint8_t pointer
/// @return Resulting int32_t sample
inline int32_t nativeInt32ToInt32(const uint8_t * src)
{
	int32_t rval = 0;
	std::memcpy(&rval, src, sizeof(int32_t));
	return rval;
}

/// @brief Convert int32_t sample to native endianness byte array. FOr use with readRxFrames
/// @param dst Destination pointer to write int32_t to
/// @param sample Source int32_t sample
inline void int32ToNativeInt32(uint8_t * dst, int32_t sample)
{
	std::memcpy(dst, &sample, sizeof(int32_t));
}

